function files(ir, name, entries) {
  return {
    "package.json": JSON.stringify({
      name: kebab(name), private: true, version: "0.0.0", type: "module",
      scripts: { dev: "vite", build: "tsc --noEmit && vite build", preview: "vite preview" },
      dependencies: { react: "^18.3.1", "react-dom": "^18.3.1" },
      devDependencies: {
        "@types/react": "^18.3.12", "@types/react-dom": "^18.3.1",
        "@vitejs/plugin-react": "^4.3.4", typescript: "^5.6.3", vite: "^5.4.11"
      }
    }, null, 2) + "\n",

    "tsconfig.json": JSON.stringify({
      compilerOptions: {
        target: "ES2020", lib: ["ES2020", "DOM", "DOM.Iterable"], module: "ESNext",
        moduleResolution: "bundler", jsx: "react-jsx", strict: true,
        noUnusedLocals: true, noUnusedParameters: true, noEmit: true,
        skipLibCheck: true, isolatedModules: true, resolveJsonModule: true
      },
      include: ["src"]
    }, null, 2) + "\n",

    "vite.config.ts":
      'import { defineConfig } from "vite";\n' +
      'import react from "@vitejs/plugin-react";\n\n' +
      "export default defineConfig({ plugins: [react()] });\n",

    "index.html":
      '<!doctype html>\n<html lang="en">\n  <head>\n    <meta charset="UTF-8" />\n' +
      '    <meta name="viewport" content="width=device-width, initial-scale=1.0" />\n' +
      "    <title>" + (ir.file || "Design system") + "</title>\n  </head>\n  <body>\n" +
      '    <div id="root"></div>\n    <script type="module" src="/src/main.tsx"></script>\n' +
      "  </body>\n</html>\n",

    "src/main.tsx":
      'import { StrictMode } from "react";\n' +
      'import { createRoot } from "react-dom/client";\n' +
      'import App from "./App";\n\n' +
      'createRoot(document.getElementById("root")!).render(\n' +
      "  <StrictMode>\n    <App />\n  </StrictMode>\n);\n",

    "src/App.tsx": galleryTsx(ir, entries),
    "src/app.css": APP_CSS
  };
}

function main() {
  const irPath = arg("--ir", ".penpot/ir.json");
  const outDir = path.resolve(arg("--out", "app"));
  const name = arg("--name", "design-system-gallery");

  if (!fs.existsSync(irPath)) {
    console.error("penpot-kit scaffold: no IR at " + irPath);
    process.exit(2);
  }
  const ir = JSON.parse(fs.readFileSync(irPath, "utf8"));
  const entries = resolveNames(ir);

  const written = [];
  const out = files(ir, name, entries);
  for (const [rel, content] of Object.entries(out)) {
    const dest = path.join(outDir, rel);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, content);
    written.push(rel);
  }

  console.log("Scaffolded " + name + " -> " + outDir);
  written.forEach((f) => console.log("  " + f));
  console.log("\n  " + entries.length + " components imported into the gallery");
  console.log("\nNext:");
  console.log("  penpot-kit emit --ir " + irPath + " --out " + path.join(outDir, "src", "design"));
  console.log("  cd " + outDir + " && npm install && npm run build");
}

if (require.main === module) main();
module.exports = { resolveNames, examples, galleryTsx };
