#!/usr/bin/env node
// penpot-kit app scaffold.
//
//   node scripts/emit/scaffold.js --ir .penpot/ir.json --out app [--name my-app]
//
// Generates a real, buildable Vite + React + TypeScript application wired to the design
// system, including a gallery screen that renders EVERY component at EVERY axis value.
//
// The gallery is not a demo. It is the consistency test:
//
//   * if a component's generated props do not typecheck, `tsc` fails
//   * if two components disagree about a token name, the CSS variable resolves to nothing
//   * if the theme layer is broken, the dark toggle visibly does not switch
//
// A design system that cannot compile its own gallery is not a system yet.

"use strict";

const fs = require("fs");
const path = require("path");

function arg(flag, def) {
  const i = process.argv.indexOf(flag);
  return i > -1 && process.argv[i + 1] ? process.argv[i + 1] : def;
}

const kebab = (s) => String(s)
  .replace(/([a-z0-9])([A-Z])/g, "$1-$2")
  .replace(/[\s_.]+/g, "-")
  .toLowerCase();
const pascal = (s) => String(s)
  .replace(/[^a-zA-Z0-9]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ""))
  .replace(/^(.)/, (m) => m.toUpperCase());
const camel = (s) => kebab(s).replace(/-([a-z0-9])/g, (_, c) => c.toUpperCase());

const BOOLY = [["no", "yes"], ["false", "true"], ["off", "on"]];
const isBool = (vals) => {
  if (vals.length !== 2) return false;
  const low = vals.map((v) => String(v).toLowerCase()).sort();
  return BOOLY.some((p) => p[0] === low[0] && p[1] === low[1]);
};
const truthy = (vals) => vals.find((v) => /^(yes|true|on)$/i.test(v));

// Resolve component names the same way the emitter does, so the gallery imports the files
// that were actually written. Getting this wrong produces a gallery that cannot resolve
// its own imports.
function resolveNames(ir) {
  const used = new Map();
  return (ir.components || []).map((c) => {
    let chosen = (c.connect && c.connect.name) || c.name;
    if (used.has(chosen)) {
      let cand = c.page && c.page !== used.get(chosen).page ? c.page + " " + chosen : null;
      if (!cand || used.has(cand)) {
        let n = 2;
        while (used.has(chosen + " " + n)) n++;
        cand = chosen + " " + n;
      }
      chosen = cand;
    }
    used.set(chosen, { page: c.page });
    return { comp: c, Name: pascal(chosen), file: pascal(chosen) };
  });
}

// One JSX example per axis-value combination, capped so a 12-variant component does not
// produce an unreadable wall.
function examples(entry, cap) {
  const { comp, Name } = entry;
  const axes = Object.entries(comp.axes || {});
  if (!axes.length) return ["<" + Name + " />"];

  let combos = [{}];
  for (const [axis, vals] of axes) {
    const next = [];
    for (const base of combos) {
      for (const v of vals) {
        next.push(Object.assign({}, base, { [axis]: v }));
        if (next.length >= cap) break;
      }
      if (next.length >= cap) break;
    }
    combos = next;
  }

  return combos.slice(0, cap).map((combo) => {
    const props = axes.map(([axis, vals]) => {
      const v = combo[axis];
      if (v === undefined) return null;
      if (isBool(vals)) return v === truthy(vals) ? camel(axis) : null;   // bare prop = true
      return camel(axis) + '="' + kebab(v) + '"';
    }).filter(Boolean).join(" ");

    const isButton = /button$/i.test(comp.name);
    const label = isButton ? Name : null;
    return "<" + Name + (props ? " " + props : "") +
      (label ? ">" + label + "</" + Name + ">" : " />");
  });
}

function galleryTsx(ir, entries) {
  const imports = entries.map((e) =>
    'import { ' + e.Name + ' } from "./design/' + e.file + '";').join("\n");

  const sections = entries.map((e) => {
    const ex = examples(e, 12);
    const axes = Object.entries(e.comp.axes || {})
      .map(([a, v]) => a + ": " + v.join(" | ")).join("   ·   ") || "no variants";
    return [
      '      <section className="gallery__section">',
      '        <header className="gallery__head">',
      "          <h2>" + e.Name + "</h2>",
      '          <p className="gallery__axes">' + axes + "</p>",
      "        </header>",
      '        <div className="gallery__row">',
      ex.map((x) => "          " + x).join("\n"),
      "        </div>",
      "      </section>"
    ].join("\n");
  }).join("\n\n");

  const themes = Object.keys(ir.tokens.resolvedByTheme || { Light: 1 });

  return `// GENERATED by penpot-kit. Regenerate: penpot-kit scaffold
//
// This gallery renders every component at every axis value. It is the consistency test:
// if the design system is coherent, this file typechecks and every surface below responds
// to the theme toggle. If it does not, something drifted.
import { useEffect, useState } from "react";
import "./design/tokens.css";
import "./app.css";
${imports}

const THEMES = ${JSON.stringify(themes.map((t) => kebab(t)))} as const;
type Theme = (typeof THEMES)[number];

export default function App() {
  const [theme, setTheme] = useState<Theme>(THEMES[0]);

  useEffect(() => {
    document.documentElement.setAttribute("data-theme", theme);
  }, [theme]);

  return (
    <div className="gallery">
      <header className="gallery__top">
        <div>
          <h1>${ir.file || "Design system"}</h1>
          <p className="gallery__meta">
            ${(ir.components || []).length} components ·{" "}
            ${(ir.components || []).reduce((a, c) => a + (c.variants || []).length, 0)} variants ·{" "}
            ${ir.tokens.values.length} tokens
          </p>
        </div>
        <div className="gallery__themes">
          {THEMES.map((t) => (
            <button
              key={t}
              className={"gallery__theme" + (t === theme ? " is-active" : "")}
              onClick={() => setTheme(t)}
            >
              {t}
            </button>
          ))}
        </div>
      </header>

${sections}
    </div>
  );
}
`;
}

